import { Router } from "express";
import bcrypt from "bcryptjs";
import { missingFields } from "../validation.js";

export default function authRoutes(users) {
  const router = Router();

// POST /signup -> validate, check duplicate, insert document
  router.post("/signup", async (req, res) => {
    if(missingFields(req.body, ["f_name", "l_name", "username", "password"])) {
        return res.status(400).json({ message: "All signup fields are required." });
    }

    const { f_name, l_name, password } = req.body;
    const username = req.body.username.trim();

    try {
        // findOne() -> existing username or null
        if(await users.findOne({ username })) {
        return res.status(409).json({ message: "That username is already taken." }); // 409 Conflict, username already exists
        }

        // hash password
        const passwordHash = await bcrypt.hash(password, 10);
        // insertOne() -> users collection; _id generated by MongoDB
        await users.insertOne({ f_name: f_name.trim(), l_name: l_name.trim(), username, password: passwordHash });
        return res.status(201).json({ message: "Account created! You can log in now." });
    } catch (error) {
        // 11000, thrown by MongoDB, means duplicate key error 
        // Unique index also catches simultaneous duplicate signups
        if(error.code === 11000) return res.status(409).json({ message: "That username is already taken." });
        console.error("Signup failed:", error);
        return res.status(500).json({ message: "Server or database error. Please try again." });
    }
  });

// POST /login -> find username, compare submitted password
  router.post("/login", async (req, res) => {
    if(missingFields(req.body, ["username", "password"])) {
        return res.status(400).json({ message: "Username and password are required." }); // 400 bad request
    }

    try {
        const user = await users.findOne({ username: req.body.username.trim() }); // MongoDB query
        if(!user) return res.status(401).json({ message: "Username does not exist." });

        const matches = await bcrypt.compare(req.body.password, user.password); // hash comparison
        if(!matches) return res.status(401).json({ message: "Incorrect password." });

        // acknowledgement only
        return res.json({ message: "Login successful!" });
    } catch (error) {
        console.error("Login failed:", error);
        return res.status(500).json({ message: "Server or database error. Please try again." });
    }
  });

  return router;
}
